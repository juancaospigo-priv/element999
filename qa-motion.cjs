await page.getByRole('tab',{name:'Agentes de IA',exact:true}).click();
assert.equal(await page.getByRole('tab',{name:'Agentes de IA',exact:true}).getAttribute('aria-selected'),'true');
await page.getByRole('tab',{name:'Agentes de IA',exact:true}).press('ArrowRight');
assert.equal(await page.getByRole('tab',{name:'Software & procesos',exact:true}).getAttribute('aria-selected'),'true');
await page.getByRole('tab',{name:'Web & captación',exact:true}).click();
